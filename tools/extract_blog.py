#!/usr/bin/env python3
"""Extract article body HTML from the legacy static blog and emit a TS data file.

- Pulls the <article> inner HTML of each legacy post
- Remaps legacy URLs to the new route structure
- Strips legacy article-footer/nav blocks that don't belong in the new layout
- Writes src/data/post-content.ts
"""
import json
import re
import html as htmllib
from pathlib import Path

REPO = Path("/home/z/my-project/repos/victor-portfolio/blog")
OUT = Path("/home/z/my-project/src/data/post-content.ts")

posts = json.loads((REPO / "posts.json").read_text())["posts"]


def extract(path: Path) -> str:
    src = path.read_text()
    m = re.search(r"<article[^>]*>(.*?)</article>", src, re.S)
    if not m:
        m = re.search(r'<main[^>]*>(.*?)</main>', src, re.S)
    body = m.group(1)

    # Drop legacy "back to blog" links and share/footer blocks
    body = re.sub(r'<div class="article-nav".*?</div>', "", body, flags=re.S)
    body = re.sub(r'<a href="/blog/"[^>]*>.*?</a>', "", body, flags=re.S)
    body = re.sub(r'class="article-meta.*?"', 'class="hidden"', body)

    # Remap legacy internal URLs to new routes
    body = body.replace('href="/blog/articles/', 'href="/blog/')
    body = body.replace('.html"', '"')
    body = body.replace('href="/projects/keja-ai/"', 'href="/work/keja-ai"')
    body = body.replace('href="/projects/tapi-learn/"', 'href="/work/tapi-learn"')
    body = body.replace('href="/projects/"', 'href="/work"')

    # Legacy inline styles reference vars that no longer exist; strip them so
    # the new .article prose styles take over.
    body = re.sub(r'\s*style="[^"]*"', "", body)

    # Collapse excess whitespace
    body = re.sub(r"\n\s*\n\s*\n+", "\n\n", body)
    return body.strip()


entries = []
for p in posts:
    slug = p["slug"]
    f = REPO / "articles" / f"{slug}.html"
    if not f.exists():
        print(f"!! missing article html for {slug}")
        continue
    body = extract(f)
    entries.append((slug, body))
    print(f"ok {slug}: {len(body)} chars")

def ts_escape(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)

parts = [
    "// AUTO-GENERATED by scripts/extract_blog.py — do not edit by hand.",
    "// Source: legacy static blog (gadda00/victor-portfolio), content migrated verbatim.",
    "",
    "export const postContent: Record<string, string> = {",
]
for slug, body in entries:
    parts.append(f"  {ts_escape(slug)}: {ts_escape(body)},")
parts.append("};")
parts.append("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(parts))
print(f"\nwrote {OUT} ({OUT.stat().st_size} bytes, {len(entries)} posts)")
